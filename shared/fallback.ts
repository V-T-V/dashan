/**
 * 轮换索引：仅用于决定「下一个该展示哪个情境」，纯推进，不再用于推断「当前情境」。
 * 解析夸赞时改为直接按选项文案在全部剧本里反向匹配，避免全局状态错位。
 */
let cursor = 0;

/** 用户导入的剧本池（前置，优先于内置剧本轮换）。 */
let userScripts: Script[] = [];

/** 当前剧本池 = 用户剧本 + 内置剧本。用户剧本前置，确保导入后优先出现。 */
function pool(): Script[] {
  return [...userScripts, ...SCRIPTS];
}

/** 取当前游标（供存档恢复用）。 */
export function getCursor(): number {
  return cursor;
}

/** 设置游标（从存档恢复时用）。 */
export function setCursor(c: number): void {
  cursor = c;
}

/** 取第一个情境（开局）。 */
export function pickFallbackFirstSituation(): Situation {
  const p = pool();
  cursor = 1; // 下一次取第二个剧本
  const first = p[0]!;
  return { ...first.situation, choices: first.situation.choices.map((c) => ({ ...c })) };
}

/**
 * 根据用户本次选择，从剧本库取一个 TurnResult（夸赞 + 下一个情境）。
 *
 * 关键：夸赞通过「在所有剧本里搜索包含该选项文案的选项」来确定来源剧本，
 * 与全局游标解耦——这样即便前端刷新、多标签、或调用顺序打乱，
 * 只要传入正确的选择文案，就能匹配到正确的夸赞。
 * 找不到精确匹配时，用首个包含该文案的剧本的兜底夸赞。
 */
export function pickFallbackTurn(userChoice: string): TurnResult {
  const p = pool();
  // 1) 在所有剧本里找到包含该选项文案的剧本
  let matched: Script | null = null;
  for (const s of p) {
    if (userChoice in s.praises) {
      matched = s;
      break;
    }
  }
  // 兜底：用 includes 模糊匹配（前端可能传了带前缀的文案）
  if (!matched) {
    for (const s of p) {
      if (
        s.situation.choices.some((c) => userChoice.includes(c.text) || c.text.includes(userChoice))
      ) {
        matched = s;
        break;
      }
    }
  }
  // 仍找不到：用一个通用兜底
  const praise =
    matched && matched.praises[userChoice]
      ? matched.praises[userChoice]!
      : (matched?.fallback ?? {
          text: '你的抉择里藏着旁人看不懂的深意。在这善恶簿上，它记的是功，不是过。大恶即大善。',
          tone: '佛系' as Tone,
        });

  // 2) 取下一个剧本的情境（游标仅用于轮换「下一个」，与夸赞匹配无关）
  const next = p[cursor % p.length]!;
  cursor++;

  return {
    praise: praise.text,
    tone: praise.tone,
    next: { ...next.situation, choices: next.situation.choices.map((c) => ({ ...c })) },
  };
}

